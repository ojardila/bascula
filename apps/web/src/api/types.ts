/* -- plots ----------------------------------------------------------- */

/**
 * `PUT /v1/plots/{id}/boundary` answers `{plot, overlaps}` — NOT a plot.
 *
 * `overlaps` names the other lots this shape now runs into. It is a warning
 * and never a refusal: the server stores the polygon and says what it saw,
 * because two lots that touch are sometimes a slip of the mouse and sometimes
 * a terrace above a coffee lot, and only the owner knows which.
 *
 * `plot.crops` is EMPTY here: the handler returns the plot's own columns
 * without re-joining what is planted in it.
 */
export interface BoundaryResult {
  plot: Plot;
  overlaps: CatalogItem[];
}

export interface PlotCrop {
  id: Uuid;
  cropTypeId: Uuid;
  cropTypeName: string;
  varietyId: Uuid | null;
  varietyName: string | null;
  areaHa: number | null;
  plantedAt: DayISO | null;
}

export interface Plot {
  id: Uuid;
  name: string;
  department: string;
  municipality: string;
  /**
   * What the owner declared, and NULL when they declared nothing.
   *
   * The adapter used to write `p.areaHa ?? 0`, which turned an unknown area
   * into "0,00 ha" on the list and on the lot's own file — and then added that
   * zero into the farm's declared total, understating it with no sign that
   * anything was missing. `AreaComparison` has always accepted a null here;
   * the `?? 0` was destroying a distinction the components downstream were
   * already built to show.
   */
  areaHa: number | null;
  /**
   * What PostGIS measured of the drawn polygon. Null until one is drawn. Both
   * figures are returned and both are shown: they always disagree, and
   * choosing one for the owner is deciding which of them lies.
   */
  computedAreaHa: number | null;
  /**
   * GeoJSON geometry, straight from the server, and deliberately `unknown`.
   *
   * Nothing on the wire is checked, so a screen that types this as a Polygon
   * is asserting something no code verified. `asGeometry` in `lib/geo.ts` is
   * the one door in: it either hands back a geometry or a null, and the map
   * draws nothing rather than drawing `undefined`.
   */
  boundary: unknown | null;
  crops: PlotCrop[];
  status: RecordStatus;
}

export interface PlotInput {
  id: Uuid;
  name: string;
  department: string;
  municipality: string;
  areaHa: number;
  /**
   * The shape drawn on the map, as a GeoJSON Polygon, or absent when the form
   * never opened the map. ABSENT AND NULL MEAN THE SAME THING to the server
   * (`hasBoundary` treats a null as "not sent"), which is deliberate: an edit
   * to a plot's name must not be able to erase a polygon by omission.
   */
  boundary?: Geometry | null;
  crops: Array<{
    id: Uuid;
    cropTypeId: Uuid;
    varietyId: Uuid | null;
    areaHa: number | null;
    plantedAt: DayISO | null;
  }>;
}

