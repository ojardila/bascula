/**
 * A union, not an object with four optional ids.
 *
 * `expense_target` in the database is
 * `(activity_id IS NOT NULL) + (coalesce(plot_id, plot_crop_id) IS NOT NULL) = 1`.
 * Written as a union here, "charged to both" and "charged to neither" are
 * shapes the form CANNOT construct — so the constraint is a compile error
 * rather than a 400 after somebody has typed the whole thing in.
 */
export type ExpenseInput =
  | {
      id: Uuid;
      concept: string;
      amountCents: number;
      date: DayISO;
      target: "activity";
      activityId: Uuid;
      note?: string | null;
    }
  | {
      id: Uuid;
      concept: string;
      amountCents: number;
      date: DayISO;
      target: "plot";
      plotId: Uuid;
      /** Optional: a lot may have several crops and a cost may cover them all. */
      plotCropId?: Uuid | null;
      note?: string | null;
    };

