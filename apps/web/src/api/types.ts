/**
 * TWO RULES OF THE DESIGN ARE ENCODED IN THESE TYPES, not left to a comment
 * on a form somewhere.
 *
 * 1. EXISTENCIAS ARE DERIVED. `Product.stock` is readonly-by-construction:
 *    there is no `ProductInput.stock`, no `updateStock`, and nothing anywhere
 *    in this app that sends a quantity as a state. The only way a number moves
 *    is `StockMoveInput`, which appends a fact. This mirrors the ledger
 *    exactly — a balance is summed from movements on every read — and it is
 *    the same argument: a stored total is a number that eventually disagrees
 *    with the facts underneath it, and on that day nothing in the system can
 *    say which of the two is right.
 *
 * 2. AN EXPENSE HAS EXACTLY ONE TARGET. `ExpenseInput` is a discriminated
 *    union on `target`, so "charged to both" and "charged to neither" are not
 *    values this type can hold. The database says the same thing with
 *    `expense_target`; making it unrepresentable here means the form cannot
 *    submit one, rather than being told off after it tried.
 */

